/**
 * Emits the country/city data the location pickers read.
 *
 * country-state-city carries ~148k cities and is 17MB unpacked, so it stays a
 * devDependency and never reaches the browser. This turns it into two things:
 *
 *   src/constants/countries.generated.ts  — 250 countries, bundled (~8KB)
 *   public/cities/<ISO2>.json             — one file per country, fetched only
 *                                           when that country is chosen
 *
 * Run with: npm run generate:locations
 */
import { writeFileSync, mkdirSync, rmSync, readdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import pkg from 'country-state-city'

const { Country, City } = pkg
const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const citiesDir = join(root, 'public', 'cities')

rmSync(citiesDir, { recursive: true, force: true })
mkdirSync(citiesDir, { recursive: true })

/**
 * The upstream data has gaps, and they are not where you would expect: Turkey
 * ships 1,278 entries covering Istanbul's districts — Beşiktaş, Kadıköy, Şişli,
 * Üsküdar — while omitting İstanbul itself, the largest city in Europe and the
 * one this platform's users are most likely to pick.
 *
 * Anything added here is merged and de-duplicated, so entries that upstream
 * later fills in cause no harm. Add a city when someone cannot find it, and
 * check with the search box first: it folds accents, so a missing "Izmir" is
 * usually a present "İzmir".
 */
const EXTRA_CITIES = {
  TR: ['İstanbul'],
}

const countries = Country.getAllCountries()
  .map(c => ({ code: c.isoCode, name: c.name }))
  .sort((a, b) => a.name.localeCompare(b.name))

let totalCities = 0
let emptyCountries = 0

for (const country of countries) {
  // Some cities repeat across a country's states; the picker only shows names,
  // so collapse them and sort for a stable, searchable list.
  const names = [...new Set([
    ...(City.getCitiesOfCountry(country.code) ?? []).map(c => c.name.trim()),
    ...(EXTRA_CITIES[country.code] ?? []),
  ].filter(Boolean))].sort((a, b) => a.localeCompare(b))

  if (names.length === 0) emptyCountries += 1
  totalCities += names.length
  writeFileSync(join(citiesDir, `${country.code}.json`), JSON.stringify(names))
}

const banner = `// GENERATED by scripts/generate-locations.mjs — do not edit by hand.
// Cities are not here: they live in public/cities/<code>.json and load on demand.
`

writeFileSync(
  join(root, 'src', 'constants', 'countries.generated.ts'),
  `${banner}
export interface CountryOption {
  code: string
  name: string
}

export const COUNTRIES: CountryOption[] = ${JSON.stringify(countries, null, 2)}

export const COUNTRY_NAMES: string[] = COUNTRIES.map(c => c.name)

const BY_NAME = new Map(COUNTRIES.map(c => [c.name, c.code]))

/** ISO code for a stored country name, or null when it predates this list. */
export function countryCodeFor(name: string): string | null {
  return BY_NAME.get(name) ?? null
}
`,
)

const written = readdirSync(citiesDir).length
console.log(JSON.stringify({
  countries: countries.length,
  cityFiles: written,
  totalCities,
  countriesWithNoCities: emptyCountries,
}, null, 2))
